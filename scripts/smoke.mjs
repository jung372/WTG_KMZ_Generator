import { _electron as electron } from '@playwright/test';
import { mkdir, readFile, writeFile, stat } from 'node:fs/promises';
import path from 'node:path';
import assert from 'node:assert/strict';
import { unzipSync, strFromU8 } from 'fflate';
const executable = process.argv[2];
await mkdir('test-results', { recursive: true });
const saved = path.resolve('test-results/한글 공백 테스트.kmz');
const launch = executable ? { executablePath: path.resolve(executable), args: [] } : { args: ['.'] };
const app = await electron.launch({ ...launch, timeout: 60000, env: { ...process.env, ELECTRON_ENABLE_LOGGING: '1' } });
const report = { executable: executable || 'development runtime', checks: [], consoleErrors: [], requests: [] };
try {
  const page = await app.firstWindow({ timeout: 60000 });
  page.setDefaultTimeout(15000);
  page.on('pageerror', e => report.consoleErrors.push(e.message));
  page.on('request', r => report.requests.push(r.url()));
  await page.getByRole('status').filter({ hasText: '저장 준비 완료' }).waitFor({ timeout: 60000 });
  await page.locator('canvas').waitFor();
  await page.waitForTimeout(700);
  assert.equal(await page.evaluate(() => typeof window.require), 'undefined');
  assert.equal(await page.evaluate(() => typeof window.desktop?.saveKmz), 'function');
  assert.equal(await page.locator('.graphics-error').count(), 0);
  report.checks.push('Packaged renderer, module worker, WebGL and isolated bridge loaded');
  report.generations = [];
  for (let i = 0; i < 10; i++) {
    await page.getByRole('button', { name: '미리보기 생성 / 적용' }).click();
    await page.getByRole('status').filter({ hasText: '저장 준비 완료' }).waitFor();
    const summary = await page.locator('.export-panel p').innerText();
    report.generations.push(Number(summary.match(/생성 ([\d.]+)초/)[1]));
  }
  report.generationP95Seconds = [...report.generations].sort((a,b) => a-b)[9];
  report.performanceScope = '10 worker geometry+KMZ runs; rounded UI timing, excludes preview frame and disk save';
  assert.ok(report.generationP95Seconds <= 5);
  await page.screenshot({ path: 'test-results/app-preview.png', fullPage: true });
  // Mock only the native dialog in the test process; production IPC and actual file write remain exercised.
  await app.evaluate(({ dialog }, target) => { dialog.showSaveDialog = async () => ({ canceled: false, filePath: target }); }, saved);
  await page.getByRole('button', { name: 'KMZ 파일 저장' }).click();
  await page.locator('.saved-path').waitFor();
  const zip = unzipSync(await readFile(saved));
  assert.equal(Object.keys(zip).length, 2);
  assert.match(strFromU8(zip['doc.kml']), /<heading>0<\/heading>/);
  assert.ok((await stat(saved)).size < 5 * 1024 * 1024);
  report.checks.push('Native save IPC writes valid KMZ in Korean/space path');
  await app.evaluate(({ dialog }) => { dialog.showSaveDialog = async () => ({ canceled: true, filePath: undefined }); });
  await page.getByRole('button', { name: 'KMZ 파일 저장' }).click();
  await page.getByText('저장을 취소했습니다. 다시 저장할 수 있습니다.').waitFor();
  report.checks.push('Save cancellation preserves input and allows retry');
  await page.getByLabel('허브 높이', { exact: true }).fill('150');
  assert.equal(await page.getByRole('button', { name: 'KMZ 파일 저장' }).isDisabled(), true);
  await page.getByRole('button', { name: '미리보기 생성 / 적용' }).click();
  await page.getByRole('status').filter({ hasText: '저장 준비 완료' }).waitFor();
  await page.getByLabel('주풍향', { exact: true }).fill('90');
  await page.getByRole('button', { name: '미리보기 생성 / 적용' }).click();
  await page.getByRole('status').filter({ hasText: '저장 준비 완료' }).waitFor();
  await app.evaluate(({ dialog }, target) => { dialog.showSaveDialog = async () => ({ canceled: false, filePath: target }); }, saved);
  await page.getByRole('button', { name: 'KMZ 파일 저장' }).click();
  await page.locator('.saved-path').waitFor();
  const changed = strFromU8(unzipSync(await readFile(saved))['doc.kml']);
  assert.match(changed, /<heading>90<\/heading>/); assert.match(changed, /name="hubHeightM"><value>150<\/value>/);
  report.checks.push('Dirty result cannot save; regenerated H150/heading90 saved correctly');
  await page.getByLabel('위도', { exact: true }).fill('91');
  await page.getByRole('button', { name: '미리보기 생성 / 적용' }).click();
  await page.getByRole('alert').filter({ hasText: '-90~90' }).waitFor();
  assert.equal(await page.getByRole('button', { name: 'KMZ 파일 저장' }).isDisabled(), true);
  report.checks.push('Invalid coordinate blocks generation and export');
  await page.getByLabel('위도', { exact: true }).fill('36');
  await page.getByLabel('허브 높이', { exact: true }).fill('70');
  await page.getByRole('button', { name: '미리보기 생성 / 적용' }).click();
  await page.getByRole('status').filter({ hasText: '저장 준비 완료' }).waitFor();
  assert.equal(await page.getByRole('button', { name: 'KMZ 파일 저장' }).isDisabled(), true);
  await page.locator('.clearance input').check();
  assert.equal(await page.getByRole('button', { name: 'KMZ 파일 저장' }).isEnabled(), true);
  report.checks.push('Below-ground rotor requires explicit acknowledgement');
  await page.getByRole('button', { name: '사용 안내', exact: true }).click();
  await page.getByRole('dialog').waitFor(); await page.getByRole('button', { name: '닫기' }).click();
  await page.setViewportSize({ width: 960, height: 720 });
  await page.screenshot({ path: 'test-results/app-compact.png', fullPage: true });
  assert.deepEqual(report.consoleErrors, []);
  assert.ok(report.requests.every(url => url.startsWith('wtg://bundle/')));
  report.checks.push('Help, compact layout, no renderer exception or remote requests');
  report.runtime = await app.evaluate(() => process.versions);
  report.completedAt = new Date().toISOString(); report.status = 'passed';
} catch (error) { report.status = 'failed'; report.error = String(error); const page = app.windows()[0]; if (page) { report.body = await page.locator('body').innerText().catch(() => 'unavailable'); await page.screenshot({ path: 'test-results/failure.png' }).catch(() => {}); } throw error; }
finally { await writeFile('test-results/smoke-report.json', JSON.stringify(report, null, 2)); await app.close(); }
console.log(JSON.stringify(report, null, 2));
